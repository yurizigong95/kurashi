function parseSlots(s){
  var out = [], last = "月";
  s.split(",").forEach(function(t){
    t = t.trim();
    var m = t.match(/^([月火水木金土])?([1-7])$/);
    if(!m) return;
    var d = m[1] || last; last = d;
    out.push({d:d, p:parseInt(m[2],10)});
  });
  return out;
}

